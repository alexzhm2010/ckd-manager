-- ============================================================
-- 健康档案云端数据表
--
-- 设计要点：历史基线数据、每次导入的报告、手动补录，全部存放在
-- 同一张 facts 表里；趋势图等所有展示只读取这张表。
--
--   kind = 'lab'    每一行是一天一个追踪指标（会进趋势图）
--   kind = 'rpt'    每一行是某份报告里的一个检验项目（含正常项）
--   kind = 'block'  用药/复查/症状/日志等整块数据，一行一份
--
-- 在 Supabase 控制台的 SQL Editor 里整段执行即可。
-- ============================================================

create table if not exists public.facts (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null default auth.uid() references auth.users(id) on delete cascade,
  uid         text not null,               -- 业务唯一键，如 lab|2026-10-29|egfr
  kind        text not null,               -- lab / rpt / block
  date        text,                        -- 统一按 YYYY-MM-DD 文本保存
  key         text,                        -- 追踪指标 key（egfr、crea…）
  name        text,
  value_num   double precision,            -- 数值型结果
  value_text  text,                        -- 非数值结果（如 2+、阴性）
  unit        text,
  ref_lo      double precision,
  ref_hi      double precision,
  flag        text,                        -- high / low / null
  source      text,                        -- seed（历史基线）/ manual / import
  raw         double precision,            -- OCR 修正前的原值
  meta        jsonb not null default '{}'::jsonb,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint facts_user_uid_key unique (user_id, uid)
);

create index if not exists facts_user_kind_date_idx
  on public.facts (user_id, kind, date desc);

-- 每个账号只能看到自己的行
alter table public.facts enable row level security;

drop policy if exists "facts own rows" on public.facts;
create policy "facts own rows" on public.facts
  for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

revoke all on public.facts from anon;
grant select, insert, update, delete on public.facts to authenticated;
